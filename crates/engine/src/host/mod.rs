/// The types and values the web host shares with the engine, in
/// TypeScript: what `cargo xtask schema` writes to
/// `web/src/generated/host.ts`.
#[cfg(all(feature = "schema", not(target_arch = "wasm32")))]
pub fn typescript() -> String {
    use crate::tooling::{constant, declarations};
    let schema =
        |schema: schemars::Schema| serde_json::to_value(schema).expect("schemas serialize");
    let mut output = String::from(
        "// Generated by `cargo xtask schema` from Rust's `engine::host`; do not edit.\n",
    );
    output.push_str(&declarations(
        &schema(schemars::schema_for!(Distribution)),
        "Distribution",
    ));
    output.push_str(&declarations(
        &schema(schemars::schema_for!(PanicReport)),
        "PanicReport",
    ));
    output.push_str(&declarations(
        &schema(schemars::schema_for!(AdapterStatus)),
        "AdapterStatus",
    ));
    for (name, value) in [
        ("PANIC_PREFIX", PANIC_PREFIX),
        ("PANIC_GLOBAL", PANIC_GLOBAL),
    ] {
        output.push_str(&constant(
            name,
            &format!("Rust's `engine_panic::{name}`."),
            &value.into(),
        ));
    }
    for (name, doc, value) in policy::constants() {
        output.push_str(&constant(name, &doc, &value));
    }
    let phases: serde_json::Map<String, serde_json::Value> = FramePhase::ALL
        .iter()
        .map(|&(phase, name)| (name.to_owned(), (phase as u32).into()))
        .collect();
    output.push_str(&constant(
        "FRAME_PHASES",
        "What an animation frame did (Rust's `engine::host::FramePhase`), by name.",
        &phases.into(),
    ));
    let settings: serde_json::Map<String, serde_json::Value> = SETTINGS
        .iter()
        .map(|setting| (setting.name.to_owned(), setting.described().into()))
        .collect();
    output.push_str(&constant(
        "HOST_SETTINGS",
        "The engine switches every host takes (Rust's `engine::host::SETTINGS`),\nwhich the engine reads from the page's parameters: each one's values and\nwhat it does.",
        &settings.into(),
    ));
    output
}
