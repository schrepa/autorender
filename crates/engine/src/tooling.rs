//! What tooling generates from Rust: TypeScript declarations of the JSON
//! schemas Rust generates, so the web host's type check catches a renamed
//! or retyped field, and the files an app generates for `cargo xtask schema`.

use std::fmt::Write;

use serde_json::Value;

/// Prints an app's generated `files`, by path from the repository root, as
/// the JSON object `cargo xtask schema` writes and lint checks: what an
/// app's `schema` binary does.
pub fn print_generated(files: &[(&str, String)]) {
    let files: serde_json::Map<String, Value> = files
        .iter()
        .map(|(path, contents)| ((*path).to_owned(), Value::from(contents.as_str())))
        .collect();
    println!("{}", Value::Object(files));
}

/// Interfaces for a schema's root object, named `root`, and each of its
/// definitions, documented by the schema's descriptions.
pub fn interfaces(schema: &Value, root: &str, source: &str) -> String {
    format!(
        "// Generated by `cargo xtask schema` from Rust's `{source}`; do not edit.\n{}",
        declarations(schema, root)
    )
}

/// [`interfaces`] without the line saying where they come from, for a file
/// that declares more.
pub fn declarations(schema: &Value, root: &str) -> String {
    let mut output = String::new();
    interface(&mut output, root, schema, false);
    for (name, definition) in schema["$defs"].as_object().into_iter().flatten() {
        interface(&mut output, name, definition, false);
    }
    output
}

/// [`interfaces`] of a message some of whose fields may be absent: a field
/// the schema does not require is optional. The definitions `imported`
/// names, by the module each comes from, are imported, not declared.
pub fn message_interfaces(
    schema: &Value,
    root: &str,
    source: &str,
    imported: &[(&str, &str)],
) -> String {
    let mut output =
        format!("// Generated by `cargo xtask schema` from Rust's `{source}`; do not edit.\n");
    for (name, module) in imported {
        writeln!(output, "import type {{ {name} }} from \"{module}\";").expect("strings write");
    }
    interface(&mut output, root, schema, true);
    for (name, definition) in schema["$defs"].as_object().into_iter().flatten() {
        if !imported.iter().any(|(imported, _)| imported == name) {
            interface(&mut output, name, definition, true);
        }
    }
    output
}

/// A TypeScript constant `name` of JSON value `value`, documented by `doc`.
pub fn constant(name: &str, doc: &str, value: &Value) -> String {
    let mut output = String::from("\n");
    comment(&mut output, "", &Value::from(doc));
    writeln!(output, "export const {name} = {value};").expect("strings write");
    output
}

/// Interface `name` of `schema`; with `optional`, the fields it does not
/// require are optional.
fn interface(output: &mut String, name: &str, schema: &Value, optional: bool) {
    output.push('\n');
    comment(output, "", &schema["description"]);
    // Enumerations and other non-objects are type aliases.
    if schema.get("properties").is_none() {
        writeln!(output, "export type {name} = {};", type_of(schema)).expect("strings write");
        return;
    }
    writeln!(output, "export interface {name} {{").expect("strings write");
    let required = schema["required"].as_array();
    for (field, property) in schema["properties"].as_object().into_iter().flatten() {
        comment(output, "  ", &property["description"]);
        let absent =
            optional && !required.is_some_and(|required| required.iter().any(|name| name == field));
        let mark = if absent { "?" } else { "" };
        writeln!(output, "  {field}{mark}: {};", type_of(property)).expect("strings write");
    }
    output.push_str("}\n");
}

fn comment(output: &mut String, indent: &str, description: &Value) {
    let Some(description) = description.as_str() else {
        return;
    };
    if !description.contains('\n') {
        writeln!(output, "{indent}/** {description} */").expect("strings write");
        return;
    }
    writeln!(output, "{indent}/**").expect("strings write");
    for line in description.lines() {
        writeln!(output, "{indent} * {line}").expect("strings write");
    }
    writeln!(output, "{indent} */").expect("strings write");
}

fn type_of(schema: &Value) -> String {
    // A schema of any value.
    if schema == &Value::Bool(true) || schema.as_object().is_some_and(serde_json::Map::is_empty) {
        return "unknown".to_owned();
    }
    if let Some(reference) = schema["$ref"].as_str() {
        return reference
            .rsplit('/')
            .next()
            .expect("references name a definition")
            .to_owned();
    }
    // String constants and enumerations are unions of their literals; numbers
    // stay numbers.
    if let Some(value) = schema.get("const").filter(|value| value.is_string()) {
        return value.to_string();
    }
    if let Some(values) = schema["enum"]
        .as_array()
        .filter(|values| values.iter().all(Value::is_string))
    {
        return values
            .iter()
            .map(Value::to_string)
            .collect::<Vec<_>>()
            .join(" | ");
    }
    if let Some(members) = schema["oneOf"].as_array().or(schema["anyOf"].as_array()) {
        let mut types: Vec<String> = Vec::new();
        for member in members {
            let member = type_of(member);
            if !types.contains(&member) {
                types.push(member);
            }
        }
        return types.join(" | ");
    }
    let types: Vec<&str> = match &schema["type"] {
        Value::String(name) => vec![name.as_str()],
        Value::Array(names) => names.iter().filter_map(Value::as_str).collect(),
        other @ (Value::Null | Value::Bool(_) | Value::Number(_) | Value::Object(_)) => {
            panic!("no TypeScript type for the schema type {other}")
        }
    };
    types
        .into_iter()
        .map(|name| match name {
            "integer" | "number" => "number".to_owned(),
            "boolean" => "boolean".to_owned(),
            "string" => "string".to_owned(),
            "null" => "null".to_owned(),
            "array" => format!("{}[]", type_of(&schema["items"])),
            // An object of any fields.
            "object" if schema.get("properties").is_none() => {
                match schema.get("additionalProperties") {
                    Some(values) if values.is_object() => {
                        format!("Record<string, {}>", type_of(values))
                    }
                    _ => "Record<string, unknown>".to_owned(),
                }
            }
            other => panic!("no TypeScript type for the schema type {other:?}"),
        })
        .collect::<Vec<_>>()
        .join(" | ")
}
