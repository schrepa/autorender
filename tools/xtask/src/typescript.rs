//! TypeScript declarations of the JSON schemas Rust generates, so the web
//! host's type check catches a renamed or retyped field.

use std::fmt::Write;

use serde_json::Value;

/// Interfaces for a schema's root object, named `root`, and each of its
/// definitions, documented by the schema's descriptions.
pub fn interfaces(schema: &Value, root: &str, source: &str) -> String {
    let mut output =
        format!("// Generated by `cargo xtask schema` from Rust's `{source}`; do not edit.\n");
    interface(&mut output, root, schema);
    for (name, definition) in schema["$defs"].as_object().into_iter().flatten() {
        interface(&mut output, name, definition);
    }
    output
}

fn interface(output: &mut String, name: &str, schema: &Value) {
    output.push('\n');
    comment(output, "", &schema["description"]);
    // Enumerations and other non-objects are type aliases.
    if schema.get("properties").is_none() {
        writeln!(output, "export type {name} = {};", type_of(schema)).expect("strings write");
        return;
    }
    writeln!(output, "export interface {name} {{").expect("strings write");
    for (field, property) in schema["properties"].as_object().into_iter().flatten() {
        comment(output, "  ", &property["description"]);
        writeln!(output, "  {field}: {};", type_of(property)).expect("strings write");
    }
    output.push_str("}\n");
}

fn comment(output: &mut String, indent: &str, description: &Value) {
    let Some(description) = description.as_str() else {
        return;
    };
    if !description.contains('\n') {
        writeln!(output, "{indent}/** {description} */").expect("strings write");
        return;
    }
    writeln!(output, "{indent}/**").expect("strings write");
    for line in description.lines() {
        writeln!(output, "{indent} * {line}").expect("strings write");
    }
    writeln!(output, "{indent} */").expect("strings write");
}

fn type_of(schema: &Value) -> String {
    if let Some(reference) = schema["$ref"].as_str() {
        return reference
            .rsplit('/')
            .next()
            .expect("references name a definition")
            .to_owned();
    }
    // String constants and enumerations are unions of their literals; numbers
    // stay numbers.
    if let Some(value) = schema.get("const").filter(|value| value.is_string()) {
        return value.to_string();
    }
    if let Some(values) = schema["enum"]
        .as_array()
        .filter(|values| values.iter().all(Value::is_string))
    {
        return values
            .iter()
            .map(Value::to_string)
            .collect::<Vec<_>>()
            .join(" | ");
    }
    if let Some(members) = schema["oneOf"].as_array().or(schema["anyOf"].as_array()) {
        let mut types: Vec<String> = Vec::new();
        for member in members {
            let member = type_of(member);
            if !types.contains(&member) {
                types.push(member);
            }
        }
        return types.join(" | ");
    }
    let types: Vec<&str> = match &schema["type"] {
        Value::String(name) => vec![name.as_str()],
        Value::Array(names) => names.iter().filter_map(Value::as_str).collect(),
        other => panic!("no TypeScript type for the schema type {other}"),
    };
    types
        .into_iter()
        .map(|name| match name {
            "integer" | "number" => "number".to_owned(),
            "boolean" => "boolean".to_owned(),
            "string" => "string".to_owned(),
            "null" => "null".to_owned(),
            "array" => format!("{}[]", type_of(&schema["items"])),
            other => panic!("no TypeScript type for the schema type {other:?}"),
        })
        .collect::<Vec<_>>()
        .join(" | ")
}
